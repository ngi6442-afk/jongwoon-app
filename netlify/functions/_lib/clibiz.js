// v456(원장 C080): 거래처 사업자번호 칸의 13자리(주민·법인등록번호 꼴) — 앱 cliBiz13(v441)과 같은 규칙의 서버 벌.
//   전각 숫자는 반각으로, 폭 없는 문자(U+200B~D·U+2060)는 지운 뒤 둘 중 하나면 참:
//   ① 쉼표·빗금으로 나눈 조각마다 띄어쓰기·줄표(- ‐ ‑ ‒ – — ― − － ㅡ)·점·밑줄·가운뎃점(· ・ ∙ •)을 빼고 숫자가 13자리 이상 이어짐
//   ② 6자리 + 구분자(띄어쓰기·줄표·점·빗금·밑줄·가운뎃점 — 없어도 됨) + 7자리(앞뒤가 숫자가 아님) — '900101/1234567'·'900101.1234567' 꼴
//   v456 2차 검토: 종전(1차 검토)은 점·빗금·밑줄을 글 전체에서 지워 빗금·점으로 나눈 사업자번호 둘('123-45-67890/234-56-78901')이 20자리로 이어져 막혔다 —
//   빗금은 쉼표처럼 번호 나눔으로 보고(①), 6+7 꼴만 빗금을 건너 따로 본다(②).
//   가린 번호('900101-1******')·10자리는 통과 · 사업자번호 둘을 띄어쓰기만으로 이으면 막힘(앱 안내 글이 쉼표·빗금으로 나누라고 함).
//   앱 쪽은 lookbehind를 못 쓰므로(옛 iOS Safari 문법 오류) 두 벌 모두 (^|\D)로 쓴다.
//   쓰는 곳: gw-data handleSave(거래처 저장 — 새로 바뀐 항목만 400 CLI_BIZ13) · _lib/ask.js(물어보기 clients 도구 — 원문을 내지 않고 검색에도 안 씀).
//   두 벌(앱·서버)은 uismoke v456가 같은 표본으로 대조한다 — 한쪽만 고치지 말 것.
function biz13(s) {
  const t = String(s == null ? '' : s)
    .replace(/[０-９]/g, function (ch) { return String.fromCharCode(ch.charCodeAt(0) - 0xFEE0); })
    .replace(/[​-‍⁠]/g, '');
  if (t.split(/[,\/]/).some(function (p) { return /\d{13}/.test(p.replace(/[\s\-‐-―−－ㅡ._·・∙•]/g, '')); })) return true;
  return /(^|\D)\d{6}[\s\-‐-―−－ㅡ.\/_·・∙•]*\d{7}(?!\d)/.test(t);
}
module.exports = { biz13 };
